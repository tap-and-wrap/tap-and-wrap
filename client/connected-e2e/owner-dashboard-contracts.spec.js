import { test, expect } from '@playwright/test';

const api = `http://127.0.0.1:${process.env.TAP_WRAP_CONTRACT_API_PORT || 4092}/api/v1`;
test('owner dashboard, unified orders and analytics render actual isolated API records; discount edits retain revisions', async ({ page, context }) => {
  const errors = [], writes = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('request', request => { if (['POST', 'PATCH'].includes(request.method()) && request.url().includes('/admin/commerce/discounts')) writes.push(request.postDataJSON()); });
  await context.route('**/*', route => ['127.0.0.1', 'localhost'].includes(new URL(route.request().url()).hostname) ? route.continue() : route.abort());
  await page.goto('/login?returnTo=%2Fadmin');
  await page.getByLabel('Email Address').fill('admin@connected.example.test');
  await page.getByLabel('Password', { exact: true }).fill('isolated-fixture-password');
  await page.getByRole('button', { name: 'Log In', exact: true }).click();
  await expect(page).toHaveURL('/admin');
  const dashboardResponse = await context.request.get(`${api}/admin/website/dashboard`);
  expect(dashboardResponse.status()).toBe(200);
  const dashboard = (await dashboardResponse.json()).data;
  expect(dashboard.recentOrders.length).toBeGreaterThan(0);
  await expect(page.getByRole('heading', { name: 'Dashboard', exact: true })).toBeVisible();
  await expect(page.locator('main')).toContainText(dashboard.recentOrders[0].orderNumber);
  await page.goto('/admin/orders');
  await expect(page.getByRole('heading', { name: 'Orders', exact: true })).toBeVisible();
  await expect(page.locator('main')).toContainText(dashboard.recentOrders[0].orderNumber);
  await page.goto('/admin/analytics');
  const analyticsResponse = await context.request.get(`${api}/admin/website/owner-analytics?days=30`);
  expect(analyticsResponse.status()).toBe(200);
  expect((await analyticsResponse.json()).data.collectionsPiastres).toBe(0);
  await expect(page.getByRole('heading', { name: 'Analytics', exact: true })).toBeVisible();
  await page.goto('/admin/discounts');
  await page.getByRole('button', { name: 'Add discount', exact: true }).click();
  await page.getByLabel('Discount name', { exact: true }).fill('Isolated owner release check');
  await page.getByLabel('Discount code', { exact: true }).fill('OWNERFIXTURE');
  await page.getByRole('textbox', { name: /^Fixed discount/ }).fill('5');
  await page.getByRole('button', { name: 'Save discount', exact: true }).click();
  await expect(page.locator('[data-sonner-toast]').filter({ hasText: 'Discount saved.' })).toBeVisible();
  expect(writes[0].expectedRevision).toBeUndefined();
  await page.getByLabel('Discount name', { exact: true }).fill('Isolated revised owner release check');
  await page.getByRole('button', { name: 'Save discount', exact: true }).click();
  await expect.poll(() => writes.length).toBe(2);
  expect(writes[1].expectedRevision).toBe(0);
  await expect(page.locator('[data-sonner-toast]').filter({ hasText: 'Discount saved.' })).toBeVisible();
  expect((await context.request.get(`${api}/admin/commerce/bundles`)).status()).toBe(410);
  expect(errors).toEqual([]);
});
