import { test, expect } from '@playwright/test';
import { mockCatalog } from './catalog-fixtures.js';
import { chooseOption } from './select-option.js';

for (const width of [320, 390, 768, 1024, 1440]) test(`shared controls, form contracts and toast layout at ${width}px`, async ({ page }, info) => {
  await mockCatalog(page); await page.setViewportSize({ width, height: 900 });
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto('/e2e/controls.html');
  const size = page.getByRole('combobox', { name: /^Size/ });
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  await expect(size).toBeFocused(); await expect(size).toHaveAttribute('aria-invalid', 'true');
  expect(await size.getAttribute('aria-describedby')).toBeTruthy();
  await size.press('Enter'); await expect(page.getByRole('option', { name: 'Unavailable', exact: true })).toHaveAttribute('aria-disabled', 'true');
  await page.keyboard.press('s'); await page.keyboard.press('Enter');
  await expect(size).toContainText('Small'); await expect(size).not.toHaveAttribute('aria-invalid', 'true');
  const category = page.getByRole('combobox', { name: /^Category/ });
  await category.click(); await page.getByRole('combobox', { name: 'Search options', exact: true }).fill('category 12');
  await expect(page.getByRole('option')).toHaveCount(1);
  await page.keyboard.press('ArrowDown'); await page.keyboard.press('Enter'); await expect(category).toContainText('Fixture category 12');
  await page.getByRole('radio', { name: 'Second', exact: true }).check();
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  await expect(page.getByLabel('Submitted fields')).toHaveText('{"size":"small","category":"category-12","segment":"two"}');
  await expect(page.getByText('Changes saved.', { exact: true })).toBeVisible();
  const toast = page.locator('[data-sonner-toast]').first();
  await expect.poll(() => toast.evaluate(element => Number(getComputedStyle(element).opacity))).toBe(1);
  await page.screenshot({ path: info.outputPath(`controls-toast-success-${width}.png`) });
  const box = await toast.boundingBox(); expect(box.y).toBeGreaterThan(500); expect(box.x).toBeGreaterThanOrEqual(0); expect(box.x + box.width).toBeLessThanOrEqual(width);
  await page.getByRole('button', { name: 'Server validation', exact: true }).click();
  await expect(size).toBeFocused(); await expect(size).toHaveAttribute('aria-invalid', 'true');
  await expect(page.getByRole('alert')).toContainText('Select an available size.');
  await page.getByRole('button', { name: 'Open control dialog', exact: true }).click();
  const dialog = page.getByRole('dialog', { name: 'Control dialog', exact: true });
  await chooseOption(dialog.getByRole('combobox'), 'two'); await expect(dialog.getByRole('combobox')).toContainText('Second option');
  await page.keyboard.press('Escape'); await expect(dialog).toHaveCount(0);
  await expect(page.getByRole('button', { name: 'Open control dialog', exact: true })).toBeFocused();
  await page.getByRole('button', { name: 'Show error toast' }).click();
  await expect(page.getByText('Could not save. Your entries are still here.', { exact: true })).toBeVisible();
  await expect.poll(() => page.locator('[data-sonner-toast][data-type=error]').evaluate(element => Number(getComputedStyle(element).opacity))).toBe(1);
  await page.screenshot({ path: info.outputPath(`controls-toast-error-${width}.png`) });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  expect(errors).toEqual([]);
});
